BEGIN;

-- A1: Keep bans distinct from deactivation and temporary locks.
ALTER TABLE app_user
    DROP CONSTRAINT chk_app_user_status,
    ADD CONSTRAINT chk_app_user_status CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'LOCKED', 'BANNED'));

-- A2: Give the application a version it can increment to end open sessions.
ALTER TABLE app_user
    ADD COLUMN session_version INTEGER NOT NULL DEFAULT 0;

-- A3: Store warehouse shortage reports and the decisions that follow them.
CREATE TABLE shortage_case (
    shortage_case_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT NOT NULL REFERENCES customer_order(order_id),
    product_id            BIGINT NOT NULL REFERENCES product(product_id),
    reported_by_worker_id BIGINT NOT NULL REFERENCES app_user(user_id),
    missing_quantity      INTEGER NOT NULL CHECK (missing_quantity > 0),
    report_note           VARCHAR(600),
    case_status           VARCHAR(40) NOT NULL DEFAULT 'OPEN',
    reported_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decision              VARCHAR(40),
    decided_by_admin_id   BIGINT REFERENCES app_user(user_id),
    decided_at            TIMESTAMPTZ,
    decision_note         VARCHAR(300),
    resolved_by_worker_id BIGINT REFERENCES app_user(user_id),
    resolved_at           TIMESTAMPTZ,
    CONSTRAINT chk_shortage_case_status CHECK (case_status IN ('OPEN', 'WAITING_RESTOCK', 'CANCELLED', 'RESOLVED')),
    CONSTRAINT chk_shortage_case_decision CHECK (decision IN ('WAIT_FOR_RESTOCK', 'CANCEL_AND_REFUND'))
);

CREATE INDEX idx_shortage_case_status ON shortage_case(case_status);
CREATE INDEX idx_shortage_case_order ON shortage_case(order_id);
CREATE UNIQUE INDEX uq_open_shortage_case
    ON shortage_case(order_id, product_id)
    WHERE case_status IN ('OPEN', 'WAITING_RESTOCK');

-- A4: Keep a history of delivery responsibility separate from physical custody.
CREATE TABLE delivery_assignment_history (
    assignment_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id              BIGINT NOT NULL REFERENCES delivery_package(package_id),
    previous_worker_user_id BIGINT REFERENCES app_user(user_id),
    new_worker_user_id      BIGINT NOT NULL REFERENCES app_user(user_id),
    assigned_by_admin_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    assigned_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reason                  VARCHAR(300) NOT NULL
);

CREATE INDEX idx_delivery_assignment_package ON delivery_assignment_history(package_id, assigned_at);

-- A5: Track whether a request came through tracking or was recorded by an Admin.
ALTER TABLE client_instruction
    ADD COLUMN source VARCHAR(30) NOT NULL DEFAULT 'TRACKING_PAGE',
    ADD COLUMN recorded_by_user_id BIGINT REFERENCES app_user(user_id),
    ADD CONSTRAINT chk_client_instruction_source CHECK (source IN ('TRACKING_PAGE', 'ADMIN_MANUAL'));

-- A6: Store the reason for rejection or an optional note on approval.
ALTER TABLE client_instruction
    ADD COLUMN resolution_note VARCHAR(300);

-- A7: Prevent two accounts whose usernames differ only by letter case.
CREATE UNIQUE INDEX uq_app_user_username_lower ON app_user(LOWER(username));

COMMIT;
