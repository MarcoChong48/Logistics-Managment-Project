-- Logistics Management System: PostgreSQL schema v1 (team REVIEW DRAFT)
-- Based on the 25-table LMS Database Draft v0.4, with practical corrections.
-- Java 21 / Spring Boot 4.1.2 / PostgreSQL 17; no Flyway required.
-- Apply to a NEW/EMPTY PostgreSQL database. Database records are not seeded here.
-- Table/column names use lowercase snake_case for straightforward Spring Data JPA mapping.
-- IMPORTANT: FK constraints alone do not enforce role permissions, order ownership,
-- valid state transitions, atomic reservation/pickup, or payment-provider idempotency.
-- Those checks MUST be implemented and tested in the service layer.

BEGIN;

-- 01. User: shared identity/account data for Client, Warehouse, Delivery, Admin.
CREATE TABLE app_user (
    user_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(80) NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    role                 VARCHAR(30) NOT NULL,
    account_status       VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    failed_login_count   INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    lock_until           TIMESTAMPTZ,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    temp_password_expires_at TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_app_user_role CHECK (role IN ('CLIENT', 'WAREHOUSE_WORKER', 'DELIVERY_WORKER', 'ADMIN')),
    CONSTRAINT chk_app_user_status CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

-- 02. ClientProfile: optional one-to-one defaults for CLIENT accounts.
CREATE TABLE client_profile (
    user_id                BIGINT PRIMARY KEY REFERENCES app_user(user_id),
    default_recipient_name VARCHAR(120),
    default_phone          VARCHAR(40),
    default_address        TEXT
);

-- 03. DeliveryWorkerProfile: proposed optional details; exact fields pending team review.
CREATE TABLE delivery_worker_profile (
    user_id          BIGINT PRIMARY KEY REFERENCES app_user(user_id),
    employee_number  VARCHAR(60) UNIQUE,
    vehicle_type     VARCHAR(60),
    vehicle_plate    VARCHAR(40),
    equipment_note   TEXT
);

-- 04. Product: catalog and current price; prices are in HKD for the initial LMS.
CREATE TABLE product (
    product_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR(60) NOT NULL UNIQUE,
    name                VARCHAR(200) NOT NULL,
    current_price       NUMERIC(12,2) NOT NULL CHECK (current_price >= 0),
    low_stock_threshold INTEGER NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0),
    listing_status      VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_listing_status CHECK (listing_status IN ('ACTIVE', 'INACTIVE'))
);

-- 05. Inventory: one warehouse, one current balance per product.
-- Avoid CHECK(reserved_stock <= physical_stock): physical shortage can be genuine.
CREATE TABLE inventory (
    product_id      BIGINT PRIMARY KEY REFERENCES product(product_id),
    physical_stock  INTEGER NOT NULL DEFAULT 0 CHECK (physical_stock >= 0),
    reserved_stock  INTEGER NOT NULL DEFAULT 0 CHECK (reserved_stock >= 0),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 06. Order: current logistics status; payment/refund are separate.
-- Named customer_order because ORDER is a SQL keyword.
CREATE TABLE customer_order (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_reference  VARCHAR(60) NOT NULL UNIQUE,
    client_user_id   BIGINT NOT NULL REFERENCES app_user(user_id),
    order_status     VARCHAR(40) NOT NULL DEFAULT 'AWAITING_PAYMENT',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    payment_deadline TIMESTAMPTZ NOT NULL,
    total_amount     NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    CONSTRAINT chk_order_deadline CHECK (payment_deadline >= created_at)
);

-- 07. OrderItem: stores historical price and durable picked quantity.
CREATE TABLE order_item (
    order_item_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES customer_order(order_id),
    product_id      BIGINT NOT NULL REFERENCES product(product_id),
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    picked_quantity INTEGER NOT NULL DEFAULT 0 CHECK (picked_quantity >= 0),
    CONSTRAINT uq_order_item_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_picked_quantity CHECK (picked_quantity <= quantity)
);

-- 08. OrderDeliveryDetail: versioned address/contact; attempts reference the used version.
CREATE TABLE order_delivery_detail (
    delivery_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL REFERENCES customer_order(order_id),
    version_no         INTEGER NOT NULL CHECK (version_no > 0),
    recipient_name     VARCHAR(120) NOT NULL,
    phone              VARCHAR(40) NOT NULL,
    address_text       TEXT NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_delivery_detail_version UNIQUE (order_id, version_no)
);

-- 09. Payment: checkout/session record. Provider callbacks and retry handling are
-- not automatic: payment logic must guard duplicate and late confirmations.
CREATE TABLE payment (
    payment_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT NOT NULL REFERENCES customer_order(order_id),
    amount             NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_status     VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    provider_reference VARCHAR(160) UNIQUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    checkout_expires_at TIMESTAMPTZ,
    ended_at           TIMESTAMPTZ,
    accepted_at        TIMESTAMPTZ,
    CONSTRAINT chk_payment_ended CHECK (ended_at IS NULL OR ended_at >= created_at),
    CONSTRAINT chk_checkout_expires CHECK (checkout_expires_at IS NULL OR checkout_expires_at >= created_at)
);

-- 10. Refund: independent from order delivery status.
CREATE TABLE refund (
    refund_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id         BIGINT NOT NULL REFERENCES payment(payment_id),
    amount             NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    refund_status      VARCHAR(40) NOT NULL DEFAULT 'REQUESTED',
    provider_reference VARCHAR(160) UNIQUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at       TIMESTAMPTZ
);

-- 11. StockReservation: specific order-item allocation with optional payment link.
CREATE TABLE stock_reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id  BIGINT NOT NULL REFERENCES order_item(order_item_id),
    payment_id     BIGINT REFERENCES payment(payment_id),
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    status         VARCHAR(30) NOT NULL DEFAULT 'HELD',
    reserved_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    released_at    TIMESTAMPTZ,
    consumed_at    TIMESTAMPTZ,
    CONSTRAINT chk_reservation_times CHECK (
        (released_at IS NULL OR released_at >= reserved_at) AND
        (consumed_at IS NULL OR consumed_at >= reserved_at)
    )
);

-- 12. PickingTask: at most one picking task per order.
CREATE TABLE picking_task (
    picking_task_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL UNIQUE REFERENCES customer_order(order_id),
    task_status      VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    start_time       TIMESTAMPTZ,
    confirm_packing_time TIMESTAMPTZ,
    CONSTRAINT chk_picking_times CHECK (
        confirm_packing_time IS NULL OR
        (start_time IS NOT NULL AND confirm_packing_time >= start_time)
    )
);

-- 13. PickingAssignmentHistory: preserve reassignment history.
CREATE TABLE picking_assignment_history (
    assignment_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    picking_task_id   BIGINT NOT NULL REFERENCES picking_task(picking_task_id),
    worker_user_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    assigned_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at          TIMESTAMPTZ,
    CONSTRAINT chk_assignment_times CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

-- 14. PickingScanHistory: rejected/unknown QR may have no matching order item.
CREATE TABLE picking_scan_history (
    scan_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    picking_task_id   BIGINT NOT NULL REFERENCES picking_task(picking_task_id),
    order_item_id     BIGINT REFERENCES order_item(order_item_id),
    worker_user_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    scanned_identifier VARCHAR(160) NOT NULL,
    scan_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    result            VARCHAR(30) NOT NULL,
    reason            VARCHAR(300),
    original_scan_id  BIGINT REFERENCES picking_scan_history(scan_id),
    CONSTRAINT chk_scan_result CHECK (result IN ('ACCEPTED', 'REJECTED', 'REVERSED')),
    CONSTRAINT chk_reversal_reference CHECK (
        (result = 'REVERSED' AND original_scan_id IS NOT NULL)
        OR (result <> 'REVERSED' AND original_scan_id IS NULL)
    )
);

-- 15. Package: one physical package per order.
CREATE TABLE delivery_package (
    package_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                  BIGINT NOT NULL UNIQUE REFERENCES customer_order(order_id),
    package_qr_code           VARCHAR(160) NOT NULL UNIQUE,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    custody_status            VARCHAR(40) NOT NULL DEFAULT 'WAREHOUSE',
    current_handler_user_id   BIGINT REFERENCES app_user(user_id)
);

-- 16. PickupList: claiming a list is not physical collection.
CREATE TABLE pickup_list (
    pickup_list_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_qr_code                VARCHAR(160) NOT NULL UNIQUE,
    created_by_worker_id        BIGINT NOT NULL REFERENCES app_user(user_id),
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status                      VARCHAR(40) NOT NULL DEFAULT 'OPEN',
    claimed_by_delivery_user_id BIGINT REFERENCES app_user(user_id),
    claimed_at                  TIMESTAMPTZ
);

-- 17. PickupListItem: (list, package) PK; a returned package may appear
-- on a NEW list for a legitimate redelivery cycle.
CREATE TABLE pickup_list_item (
    pickup_list_id      BIGINT NOT NULL REFERENCES pickup_list(pickup_list_id),
    package_id          BIGINT NOT NULL REFERENCES delivery_package(package_id),
    collection_outcome  VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    collected_at        TIMESTAMPTZ,
    cannot_collect_reason VARCHAR(300),
    PRIMARY KEY (pickup_list_id, package_id)
);

-- 18. PackageCustodyEvent: immutable custody/pickup/return history.
-- Details JSONB is provisional for return receipt data; the team may decide
-- to replace it with dedicated receipt/line tables in a later revision.
CREATE TABLE package_custody_event (
    custody_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id       BIGINT NOT NULL REFERENCES delivery_package(package_id),
    event_type       VARCHAR(50) NOT NULL,
    actor_user_id    BIGINT REFERENCES app_user(user_id),
    pickup_list_id   BIGINT REFERENCES pickup_list(pickup_list_id),
    event_time       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    details          JSONB
);

-- 19. DeliveryAttempt: separate attempt each visit; used address version fixed.
CREATE TABLE delivery_attempt (
    delivery_attempt_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id               BIGINT NOT NULL REFERENCES delivery_package(package_id),
    delivery_detail_id       BIGINT NOT NULL REFERENCES order_delivery_detail(delivery_detail_id),
    delivery_worker_user_id  BIGINT NOT NULL REFERENCES app_user(user_id),
    pickup_custody_event_id  BIGINT REFERENCES package_custody_event(custody_event_id),
    start_time               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    end_time                 TIMESTAMPTZ,
    outcome                  VARCHAR(40) NOT NULL DEFAULT 'IN_PROGRESS',
    failure_reason           VARCHAR(100),
    internal_note            VARCHAR(600),
    CONSTRAINT chk_delivery_attempt_time CHECK (end_time IS NULL OR end_time >= start_time)
);

-- 20. DeliveryProof: reference to secured file storage; do not store the
-- photo or signature bytes or public URL in this table.
CREATE TABLE delivery_proof (
    proof_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_attempt_id BIGINT NOT NULL REFERENCES delivery_attempt(delivery_attempt_id),
    proof_type          VARCHAR(30) NOT NULL,
    proof_reference     VARCHAR(512) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_proof_type CHECK (proof_type IN ('PHOTO', 'SIGNATURE'))
);

-- 21. ClientInstruction: link to a delivery address version/return event
-- where applicable; service must check they belong to this order.
CREATE TABLE client_instruction (
    instruction_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                 BIGINT NOT NULL REFERENCES customer_order(order_id),
    client_user_id           BIGINT NOT NULL REFERENCES app_user(user_id),
    delivery_detail_id       BIGINT REFERENCES order_delivery_detail(delivery_detail_id),
    return_custody_event_id  BIGINT REFERENCES package_custody_event(custody_event_id),
    instruction_type         VARCHAR(40) NOT NULL,
    status                   VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    submitted_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_by_admin_id     BIGINT REFERENCES app_user(user_id),
    resolved_at              TIMESTAMPTZ
);

-- 22. Notification: in-system notifications (no email service required).
CREATE TABLE notification (
    notification_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    order_id         BIGINT REFERENCES customer_order(order_id),
    type             VARCHAR(60) NOT NULL,
    message          VARCHAR(600) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_read          BOOLEAN NOT NULL DEFAULT FALSE
);

-- 23. StockMovement: history of physical and reserved balance deltas.
-- Service transaction must update inventory and insert stock_movement together.
CREATE TABLE stock_movement (
    movement_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT NOT NULL REFERENCES product(product_id),
    package_id         BIGINT REFERENCES delivery_package(package_id),
    custody_event_id   BIGINT REFERENCES package_custody_event(custody_event_id),
    actor_user_id      BIGINT REFERENCES app_user(user_id),
    movement_type      VARCHAR(50) NOT NULL,
    quantity_delta     INTEGER NOT NULL,
    reserved_delta     INTEGER NOT NULL DEFAULT 0,
    event_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reason             VARCHAR(300),
    CONSTRAINT chk_stock_movement_nonzero CHECK (
        quantity_delta <> 0 OR reserved_delta <> 0
    )
);

-- 24. AuditLog: only sanitized operational/admin change history.
CREATE TABLE audit_log (
    audit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  BIGINT REFERENCES app_user(user_id),
    action         VARCHAR(100) NOT NULL,
    target_type    VARCHAR(80) NOT NULL,
    target_id      VARCHAR(100) NOT NULL,
    old_value      JSONB,
    new_value      JSONB,
    event_time     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    result         VARCHAR(40) NOT NULL
);

-- 25. SecurityLog: auth, lockout/unlock, reset, authorization events.
CREATE TABLE security_log (
    security_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES app_user(user_id),
    event_type      VARCHAR(80) NOT NULL,
    event_time      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    result          VARCHAR(40) NOT NULL,
    ip_address      VARCHAR(45),
    device_info     VARCHAR(300),
    details         VARCHAR(600)
);

-- Useful indexes for common joins, lookups and history queries.
-- Postgres automatically creates indexes for PRIMARY KEY / UNIQUE columns,
-- but not for referencing FOREIGN KEY columns.
CREATE INDEX idx_order_client ON customer_order(client_user_id);
CREATE INDEX idx_order_item_order ON order_item(order_id);
CREATE INDEX idx_delivery_detail_order ON order_delivery_detail(order_id);
CREATE INDEX idx_payment_order ON payment(order_id);
CREATE INDEX idx_refund_payment ON refund(payment_id);
CREATE INDEX idx_reservation_item ON stock_reservation(order_item_id);
CREATE INDEX idx_reservation_payment ON stock_reservation(payment_id);
CREATE INDEX idx_picking_history_task ON picking_scan_history(picking_task_id, scan_time);
CREATE INDEX idx_pickup_list_item_package ON pickup_list_item(package_id);
CREATE INDEX idx_custody_package ON package_custody_event(package_id, event_time);
CREATE INDEX idx_attempt_package ON delivery_attempt(package_id, start_time);
CREATE INDEX idx_proof_attempt ON delivery_proof(delivery_attempt_id);
CREATE INDEX idx_instruction_order ON client_instruction(order_id, submitted_at);
CREATE INDEX idx_notification_recipient ON notification(recipient_user_id, created_at);
CREATE INDEX idx_stock_movement_product ON stock_movement(product_id, event_time);
CREATE INDEX idx_audit_target ON audit_log(target_type, target_id);
CREATE INDEX idx_security_user ON security_log(user_id, event_time);

-- One active warehouse picking worker per task at a time.
CREATE UNIQUE INDEX uq_active_picking_assignment
    ON picking_assignment_history(picking_task_id)
    WHERE ended_at IS NULL;
-- Prevent more than one reversal referencing the same original scan.
CREATE UNIQUE INDEX uq_scan_reversal_original
    ON picking_scan_history(original_scan_id)
    WHERE original_scan_id IS NOT NULL;

COMMIT;
