-- Delivery v4 team integration. Apply after the shared core and Admin migrations.
BEGIN;

ALTER TABLE pickup_list
    ADD COLUMN IF NOT EXISTS assigned_to_delivery_user_id BIGINT REFERENCES app_user(user_id),
    ADD COLUMN IF NOT EXISTS delivery_last_activity_at TIMESTAMPTZ;
ALTER TABLE pickup_list_item
    ADD COLUMN IF NOT EXISTS delivery_internal_note VARCHAR(600);
ALTER TABLE delivery_package
    ADD COLUMN IF NOT EXISTS delivery_detail_id BIGINT REFERENCES order_delivery_detail(delivery_detail_id),
    ADD COLUMN IF NOT EXISTS delivery_hold_reason VARCHAR(300);
ALTER TABLE inventory
    ADD COLUMN IF NOT EXISTS delivery_unavailable_stock INTEGER NOT NULL DEFAULT 0
        CHECK (delivery_unavailable_stock >= 0);
ALTER TABLE delivery_attempt
    ADD COLUMN IF NOT EXISTS delivery_managed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE delivery_proof
    ADD COLUMN IF NOT EXISTS delivery_used_for_outcome BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_delivery_pickup_pending
    ON pickup_list (assigned_to_delivery_user_id, created_at, pickup_list_id) WHERE status = 'OPEN';

CREATE TABLE IF NOT EXISTS delivery_return_receipt (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES delivery_package(package_id),
    pickup_event_id BIGINT NOT NULL REFERENCES package_custody_event(custody_event_id),
    delivery_attempt_id BIGINT REFERENCES delivery_attempt(delivery_attempt_id) ON DELETE SET NULL,
    failed_attempt BOOLEAN NOT NULL DEFAULT FALSE,
    reported_by_user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    reason VARCHAR(600) NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (status IN ('AWAITING_WAREHOUSE', 'RECEIVED')),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    received_at TIMESTAMPTZ,
    received_by_user_id BIGINT REFERENCES app_user(user_id),
    condition VARCHAR(40) CHECK (condition IN ('INTACT', 'DAMAGED')),
    receipt_event_id BIGINT REFERENCES package_custody_event(custody_event_id),
    UNIQUE (package_id, pickup_event_id)
);
CREATE INDEX IF NOT EXISTS idx_delivery_return_package ON delivery_return_receipt(package_id, return_id DESC);

CREATE TABLE IF NOT EXISTS delivery_return_line (
    return_id BIGINT NOT NULL REFERENCES delivery_return_receipt(return_id),
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    unavailable_quantity INTEGER NOT NULL CHECK (unavailable_quantity BETWEEN 0 AND quantity),
    PRIMARY KEY (return_id, product_id)
);

CREATE TABLE IF NOT EXISTS delivery_operation_result (
    actor_user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    action VARCHAR(60) NOT NULL,
    target VARCHAR(160) NOT NULL,
    request_id UUID NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    result_json JSONB NOT NULL,
    PRIMARY KEY (actor_user_id, action, target, request_id)
);

CREATE TABLE IF NOT EXISTS delivery_retained_attempt (
    retained_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES delivery_package(package_id),
    worker_id BIGINT NOT NULL REFERENCES app_user(user_id),
    outcome VARCHAR(40) NOT NULL,
    event_at TIMESTAMPTZ NOT NULL
);

COMMIT;
