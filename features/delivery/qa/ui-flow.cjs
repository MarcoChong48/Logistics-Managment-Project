const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let browser;
const baseURL = process.env.DELIVERY_TEST_URL || 'http://127.0.0.1:8080';
const evidence = path.join(__dirname, 'evidence');

// Use a fresh demo database. Every state change below goes through the real UI.
(async () => {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(baseURL, { waitUntil: 'networkidle' });
  await page.getByLabel('Username', { exact: true }).fill('ken');
  await page.getByLabel('Password', { exact: true }).fill('Delivery123!');
  await page.getByRole('button', { name: /Sign in to workspace/ }).click();
  await page.getByTestId('workspace-shell').waitFor();
  fs.mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: path.join(evidence, 'fresh-overview.png'), fullPage: true });
  await page.getByRole('button', { name: 'Warehouse pickup', exact: true }).click();
  await page.getByPlaceholder('For example, PL-1001').fill('PL-1001');
  await page.getByRole('button', { name: 'Claim list', exact: true }).click();
  await page.getByText('Claimed by you', { exact: true }).first().waitFor();
  const list = page.locator('.pickup-list').filter({ hasText: 'PL-1001' });
  await list.getByPlaceholder('Package QR code').fill('PKG-1001');
  await list.getByRole('button', { name: 'Collect package', exact: true }).click();
  await page.getByRole('button', { name: 'My deliveries', exact: true }).click();
  await page.getByRole('button', { name: 'Start delivery', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Start delivery', exact: true }).click();
  await page.getByRole('button', { name: 'Record outcome', exact: true }).click();
  const canvas = page.getByLabel('Draw recipient signature');
  await canvas.scrollIntoViewIfNeeded();
  const box = await canvas.boundingBox();
  assert.ok(box && box.width > 150);
  await page.mouse.move(box.x + 35, box.y + 65);
  await page.mouse.down();
  for (const [x,y] of [[70,40],[90,100],[120,45],[160,95],[210,60]]) await page.mouse.move(box.x + x, box.y + y, { steps: 4 });
  await page.mouse.up();
  await page.getByRole('button', { name: 'Save signature proof', exact: true }).click();
  await page.getByText('Signature', { exact: true }).first().waitFor();
  await page.screenshot({ path: path.join(evidence, 'signature-outcome.png'), fullPage: false });
  await page.getByRole('button', { name: /Confirm delivered|Save delivery result|Mark delivered/ }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm delivered', exact: true }).click();
  await page.getByRole('button', { name: 'Attempt history', exact: true }).click();
  assert.match(await page.locator('main').innerText(), /Delivered/);
  assert.match(await page.locator('main').innerText(), /Metadata only/);
  assert.equal(errors.length, 0, errors.join('\n'));
  const result = { status: 'passed', workflow: 'UI login → claim list → collect package → start delivery → draw/upload signature → confirm delivered → read-only history', pageErrors: errors, cameraHardware: 'not tested' };
  fs.writeFileSync(path.join(evidence, 'ui-flow-result.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
})().catch(async error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
